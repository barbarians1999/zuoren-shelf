def manifest_paths(output_root: Path) -> set[str]:
    manifest_path = output_root / MANIFEST_NAME
    if not manifest_path.exists():
        return set()
    manifest = read_json(manifest_path)
    if manifest.get("version") != MANIFEST_VERSION or not isinstance(manifest.get("files"), list):
        raise ValueError(f"Unsupported generated page manifest: {manifest_path}")
    result = set()
    for item in manifest["files"]:
        path = PurePosixPath(str(item))
        if path.is_absolute() or ".." in path.parts or not path.parts:
            raise ValueError(f"Unsafe path in generated page manifest: {item!r}")
        result.add(path.as_posix())
    return result


def write_generated(output_root: Path, filename: str, content: str, previous_files: set[str], current_files: set[str]) -> None:
    relative = PurePosixPath(filename)
    if relative.is_absolute() or ".." in relative.parts:
        raise ValueError(f"Unsafe output path: {filename!r}")
    target = output_root.joinpath(*relative.parts)
    if target.exists() and filename not in previous_files:
        raise FileExistsError(f"Refusing to overwrite an untracked file: {target}")
    target.parent.mkdir(parents=True, exist_ok=True)
    target.write_text(content, encoding="utf-8")
    current_files.add(relative.as_posix())


def build(repo_root: Path, output_root: Path, base_url: str) -> dict[str, int]:
    origin, base_path = split_base_url(base_url)
    base_url = origin + base_path
    data = read_json(repo_root / "book-index.json")
    all_books = data.get("books", [])
    authors = data.get("authorIndex", [])
    if not all_books:
        raise ValueError("book-index.json contains no books")

    all_books_by_id = {str(book["id"]): book for book in all_books}
    author_works = {
        str(author["id"]): visible_author_works(author, all_books_by_id)
        for author in authors
    }
    discoverable_book_ids = {str(book["id"]) for book in all_books if not book.get("authorOnly")}
    for works in author_works.values():
        for work in works:
            book_id = str(work.get("bookId", ""))
            book = all_books_by_id.get(book_id)
            if not book:
                continue
            sections = {str(section.get("id")): section for section in book.get("sections", [])}
            section = sections.get(str(work.get("sectionId", "")))
            if section and section.get("readerHidden") is not True:
                discoverable_book_ids.add(book_id)
    # An explicit dedupeGroup chooses one author-page entry, but keep every
    # book in that group discoverable so its existing static URLs still build.
    for author in authors:
        visible_groups = {
            str(work.get("dedupeGroup", "")).strip()
            for work in author_works.get(str(author["id"]), [])
            if str(work.get("dedupeGroup", "")).strip()
        }
        for work in author.get("featuredWorks", []):
            group = str(work.get("dedupeGroup", "")).strip() if isinstance(work, dict) else ""
            book_id = str(work.get("bookId", "")) if isinstance(work, dict) else ""
            if group in visible_groups and book_id in all_books_by_id:
                discoverable_book_ids.add(book_id)
    books = [book for book in all_books if str(book["id"]) in discoverable_book_ids]
    previous_files = manifest_paths(output_root)
    current_files: set[str] = set()
    urls = [base_url, base_url + "catalog/"]
    sections_by_book: dict[str, list[dict]] = {}
    article_urls: dict[tuple[str, str], str] = {}
    primary_text: dict[str, tuple[str, str]] = {}

    for book in books:
        book_id = str(book["id"])
        safe_segment(book_id, "book ID")
        entries = []
        html_by_section: dict[str, str] = {}
        section_sources: list[tuple[dict, str]] = []
        if book.get("type") != "scan":
            section_path = Path(book.get("sectionPath") or "sections")
            for section in book.get("sections", []):
                section_id = str(section.get("id", ""))
                safe_segment(section_id, f"section ID in {book_id}")
                if section.get("readerHidden") is True:
                    continue
                section_file = repo_root / section_path / f"{section_id}.json"
                if not section_file.is_file():
                    raise FileNotFoundError(f"Missing section source: {section_file}")
                source = read_json(section_file)
                source_html = str(source.get("html", ""))
                if not source_html.strip():
                    raise ValueError(f"Empty section source: {section_file}")
                # Keep the exact catalog title and authored HTML body. A heading
                # or scan page marker alone is not a standalone article.
                entry = {**section, "title": str(section.get("title") or source.get("title") or section_id)}
                section_sources.append((entry, source_html))

        for entry, source_html in section_sources:
            section_id = str(entry["id"])
            if not section_has_body(entry, source_html, str(book.get("title", ""))):
                continue
            fingerprint = normalized_article_text(source_html)
            owner = primary_text.get(fingerprint)
            if owner:
                article_urls[(book_id, section_id)] = article_url(base_url, owner[0], owner[1])
                continue
            primary_text[fingerprint] = (book_id, section_id)
            entries.append(entry)
            html_by_section[section_id] = source_html
            article_urls[(book_id, section_id)] = article_url(base_url, book_id, section_id)
        sections_by_book[book_id] = entries

        book_path = f"books/{safe_segment(book_id, 'book ID')}/index.html"
        write_generated(
            output_root,
            book_path,
            render_book_page(
                base_url=base_url,
                base_path=base_path,
                book=book,
                sections=entries,
                section_content=html_by_section,
            ),
            previous_files,
            current_files,
        )
        urls.append(book_url(base_url, book_id))

        for position, section in enumerate(entries):
            section_id = section["id"]
            text_path = (
                f"texts/{safe_segment(book_id, 'book ID')}/"
                f"{safe_segment(section_id, 'section ID')}/index.html"
            )
            write_generated(
                output_root,
                text_path,
                render_article_page(
                    base_url=base_url,
                    base_path=base_path,
                    book=book,
                    section=section,
                    section_html=html_by_section[section_id],
                    readable_sections=entries,
                    position=position,
                ),
                previous_files,
                current_files,
            )
            urls.append(article_urls[(book_id, section_id)])

    for author in authors:
        author_id = str(author["id"])
        safe_segment(author_id, "author ID")
        author_path = f"authors/{safe_segment(author_id, 'author ID')}/index.html"
        write_generated(
            output_root,
            author_path,
            render_author_page(base_url, base_path, author, author_works[str(author["id"])], article_urls),
            previous_files,
            current_files,
        )
        urls.append(author_url(base_url, author_id))

    catalog_path = "catalog/index.html"
    write_generated(
        output_root,
        catalog_path,
        render_catalog_page(base_url, base_path, books, authors, sections_by_book),
        previous_files,
        current_files,
    )

    sitemap = ET.Element(f"{{{SITEMAP_NS}}}urlset")
    for url in urls:
        item = ET.SubElement(sitemap, f"{{{SITEMAP_NS}}}url")
        ET.SubElement(item, f"{{{SITEMAP_NS}}}loc").text = url
    ET.indent(sitemap, space="  ")
    sitemap_xml = ET.tostring(sitemap, encoding="utf-8", xml_declaration=True).decode("utf-8") + "\n"
    write_generated(output_root, "sitemap.xml", sitemap_xml, previous_files, current_files)

    stale = previous_files - current_files
    for relative in sorted(stale):
        target = output_root.joinpath(*PurePosixPath(relative).parts)
        if target.is_file():
            target.unlink()
    manifest_path = output_root / MANIFEST_NAME
    manifest_path.write_text(
        json.dumps(
            {"version": MANIFEST_VERSION, "files": sorted(current_files)},
            ensure_ascii=False,
            indent=2,
        )
        + "\n",
        encoding="utf-8",
    )
    return {
        "books": len(books),
        "authors": len(authors),
        "articles": sum(len(entries) for entries in sections_by_book.values()),
        "sitemap_urls": len(urls),
        "generated_files": len(current_files),
    }


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--base-url", default=DEFAULT_BASE_URL, help=f"canonical project-site base URL (default: {DEFAULT_BASE_URL})")
    parser.add_argument("--repo-root", type=Path, default=Path(__file__).resolve().parents[1])
    parser.add_argument("--output-dir", type=Path, default=None, help="output root (default: repository root)")
    args = parser.parse_args()
    repo_root = args.repo_root.resolve()
    output_root = (args.output_dir or repo_root).resolve()
    try:
        counts = build(repo_root, output_root, args.base_url)
    except (OSError, ValueError, KeyError, json.JSONDecodeError) as error:
        print(f"search page generation failed: {error}", file=sys.stderr)
        return 1
    summary = ", ".join(f"{key}={value}" for key, value in counts.items())
    print(f"search pages generated at {output_root}: {summary}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
