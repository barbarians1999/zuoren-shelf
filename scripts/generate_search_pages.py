class TextExtractor(HTMLParser):
    """Extract readable source text without changing source markup on pages."""

    def __init__(self) -> None:
        super().__init__(convert_charrefs=True)
        self.parts: list[str] = []
        self.skip_depth = 0

    def handle_starttag(self, tag: str, attrs: list[tuple[str, str | None]]) -> None:
        if tag in {"script", "style", "noscript", "template"}:
            self.skip_depth += 1

    def handle_endtag(self, tag: str) -> None:
        if tag in {"script", "style", "noscript", "template"} and self.skip_depth:
            self.skip_depth -= 1

    def handle_data(self, data: str) -> None:
        if not self.skip_depth:
            self.parts.append(data)


def plain_text(fragment: str) -> str:
    parser = TextExtractor()
    parser.feed(fragment)
    parser.close()
    return re.sub(r"\s+", " ", " ".join(parser.parts)).strip()


def excerpt(fragment: str, limit: int = 180) -> str:
    text = plain_text(fragment)
    if len(text) <= limit:
        return text
    return text[:limit].rstrip() + "…"


def normalized_work_title(title: object) -> str:
    value = unicodedata.normalize("NFKC", str(title))
    return "".join(
        char for char in value
        if not char.isspace() and unicodedata.category(char)[0] not in {"P", "S"}
    )


def normalized_mao_title(title: object) -> str:
    return normalized_work_title(unicodedata.normalize("NFKC", str(title)).replace("刘易斯", "路易斯"))


def normalized_article_text(fragment: str) -> str:
    return re.sub(r"\s+", "", unicodedata.normalize("NFKC", plain_text(fragment)))


def section_has_body(section: dict, fragment: str, book_title: str = "") -> bool:
    """Return false for section markers that contain no text beyond their label."""
    text = normalized_work_title(normalized_article_text(fragment))
    text = re.sub(r"第\d+页", "", text)
    title = normalized_work_title(section.get("title", ""))
    book_label = normalized_work_title(re.split(r"[（(]", book_title, maxsplit=1)[0])
    labels = [label for label in (book_label, title) if label]
    while text:
        leading_label = next((label for label in labels if text.startswith(label)), None)
        if leading_label is None:
            break
        text = text[len(leading_label):]
        text = re.sub(r"第\d+页", "", text)
    return bool(text)


def _year_sort_key(work: dict) -> float:
    sort_year = work.get("sortYear")
    if sort_year is not None:
        try:
            return float(sort_year)
        except (TypeError, ValueError):
            pass
    match = re.search(r"\d{4}", str(work.get("year", "")))
    return float(match.group()) if match else float("inf")


def _mao_other_edition(work: dict, selected_titles: set[str]) -> bool:
    title = unicodedata.normalize("NFKC", str(work.get("title", "")))
    unabridged = title.startswith("〔未删节本〕")
    suffix = re.compile(r"[（(](?:原始版本|原版|讲话稿|异译本|异译|繁体(?:版)?|译本|版本[一-三\d]?|修订(?:本|版)|删节(?:本|版)|手稿|原稿)[）)]$")
    explicit_edition = unabridged or bool(suffix.search(title))
    candidates = [re.sub(r"^〔未删节本〕", "", title)]
    candidates[0] = suffix.sub("", candidates[0])
    if unabridged:
        base_title = re.split(r"[—–―]", candidates[0], maxsplit=1)[0]
        candidates.extend([base_title, base_title.replace("与", "和")])
    return any(normalized_mao_title(candidate) in selected_titles for candidate in candidates) or (
        explicit_edition
        and any(normalized_mao_title(candidate.replace("与", "和")) in selected_titles for candidate in candidates)
    )


def visible_author_works(author: dict, books_by_id: dict[str, dict]) -> list[dict]:
    """Mirror the app's current author-page ordering and version deduplication."""
    featured = [work for work in author.get("featuredWorks", []) if isinstance(work, dict)]
    if author.get("id") == "mao":
        selected = books_by_id.get("mao-selected")
        selected_id = selected.get("id") if selected else None
        by_section = {
            work.get("sectionId"): work
            for work in featured
            if work.get("bookId") == selected_id
        }
        selected_titles = {
            normalized_mao_title(section.get("title", ""))
            for section in (selected or {}).get("sections", [])
            if section.get("level") == 2
        }
        selected_works = []
        groups_started = False
        for section in (selected or {}).get("sections", []):
            if section.get("level") == 0 and re.match(r"^第[一二三四五六七]卷", str(section.get("title", ""))):
                groups_started = True
            elif section.get("level") == 2 and groups_started:
                original = by_section.get(section.get("id"), {})
                selected_works.append({
                    **original,
                    "title": section.get("title", original.get("title", "")),
                    "bookId": selected_id,
                    "sectionId": section.get("id"),
                })
        extras = [
            work for work in featured
            if work.get("bookId") != selected_id and not _mao_other_edition(work, selected_titles)
        ]
        return selected_works + extras

    positions: dict[str, int] = {}
    visible = []
    for work in sorted(featured, key=_year_sort_key):
        group = str(work.get("dedupeGroup", "")).strip()
        key = (
            f"group:{group}"
            if group
            else f"{work.get('bookId') or work.get('url')}|{normalized_work_title(work.get('title', ''))}"
        )
        existing_index = positions.get(key)
        if existing_index is None:
            positions[key] = len(visible)
            visible.append(work)
        elif work.get("recommendation") and not visible[existing_index].get("recommendation"):
            visible[existing_index] = work
    return visible


def safe_segment(value: str, field: str) -> str:
    value = str(value)
    if not SAFE_ID.fullmatch(value) or value in {".", ".."}:
        raise ValueError(f"Unsafe {field} URL segment: {value!r}")
    return quote(value, safe="-._~")


def split_base_url(base_url: str) -> tuple[str, str]:
    parsed = urlparse(base_url)
    if parsed.scheme != "https" or not parsed.netloc or parsed.query or parsed.fragment:
        raise ValueError("--base-url must be an HTTPS URL without a query or fragment")
    path = parsed.path or "/"
    if not path.startswith("/"):
        raise ValueError("--base-url must have an absolute URL path")
    path = path.rstrip("/") + "/"
    origin = f"{parsed.scheme}://{parsed.netloc}"
    return origin, path


def read_json(path: Path) -> dict:
    return json.loads(path.read_text(encoding="utf-8"))


def escape(value: object) -> str:
    return html.escape(str(value), quote=True)


def source_html_with_site_assets(fragment: str, base_path: str) -> str:
    # Existing illustrations use root-relative repository paths. The generated
    # pages are nested, so make those paths explicit beneath the Pages project.
    return re.sub(
        r"(?i)(\bsrc\s*=\s*)(['\"])(books/)",
        lambda match: f"{match.group(1)}{match.group(2)}{base_path}{match.group(3)}",
        fragment,
    )


def _source_offset(source: str, line_offsets: list[int], position: tuple[int, int]) -> int:
    line, column = position
    return line_offsets[line - 1] + column


class HeadingAnalyzer(HTMLParser):
    """Collect heading tag positions without reserializing source text."""

    def __init__(self, source: str) -> None:
        super().__init__(convert_charrefs=False)
        self.source = source
        self.line_offsets = [0]
        self.line_offsets.extend(index + 1 for index, char in enumerate(source) if char == "\n")
        self.active_headings: list[dict] = []
        self.headings: list[dict] = []

    def source_position(self) -> int:
        return _source_offset(self.source, self.line_offsets, self.getpos())

    def handle_starttag(self, tag: str, attrs: list[tuple[str, str | None]]) -> None:
        if re.fullmatch(r"h[1-6]", tag):
            self.active_headings.append({
                "tag": tag,
                "start": self.source_position(),
                "close_start": None,
            })

    def handle_endtag(self, tag: str) -> None:
        if re.fullmatch(r"h[1-6]", tag):
            index = next(
                (i for i in range(len(self.active_headings) - 1, -1, -1) if self.active_headings[i]["tag"] == tag),
                None,
            )
            if index is not None:
                heading = self.active_headings.pop(index)
                heading["close_start"] = self.source_position()
                self.headings.append(heading)

    def close(self) -> None:
        super().close()
        self.headings.extend(self.active_headings)
        self.active_headings.clear()


def _apply_edits(source: str, edits: list[tuple[int, int, str]]) -> str:
    for start, end, replacement in sorted(edits, key=lambda item: (item[0], item[1]), reverse=True):
        source = source[:start] + replacement + source[end:]
    return source


def _normalize_heading_levels(source: str) -> str:
    analyzer = HeadingAnalyzer(source)
    analyzer.feed(source)
    analyzer.close()
    headings = sorted(
        analyzer.headings,
        key=lambda block: block["start"],
    )
    if not headings:
        return source

    edits = []
    previous_source_level = None
    output_level = 1
    for heading in headings:
        source_level = int(heading["tag"][1])
        if previous_source_level is None:
            output_level = 2
        else:
            # Keep the source's relative nesting while preventing heading jumps
            # in the standalone article fragment.
            change = max(-1, min(1, source_level - previous_source_level))
            output_level = max(2, min(6, output_level + change))
        replacement = f"h{output_level}"
        if heading["tag"] != replacement:
            edits.append((heading["start"] + 1, heading["start"] + 3, replacement))
            if heading["close_start"] is not None:
                edits.append((heading["close_start"] + 2, heading["close_start"] + 4, replacement))
        previous_source_level = source_level
    return _apply_edits(source, edits)


def _normalize_inline_block_wrappers(source: str) -> str:
    """Move legacy inline emphasis inside a single block so it stays valid HTML."""
    pattern = re.compile(
        r"(?is)<(?P<inline>b|i|strong|em)\b(?P<inline_attrs>[^>]*)>\s*"
        r"<(?P<block>p|div|h[1-6])\b(?P<block_attrs>[^>]*)>"
        r"(?P<content>.*?)</(?P=block)\s*>\s*</(?P=inline)\s*>"
    )

    def replace(match: re.Match[str]) -> str:
        inline = match.group("inline")
        block = match.group("block")
        return (
            f"<{block}{match.group('block_attrs')}>"
            f"<{inline}{match.group('inline_attrs')}>{match.group('content')}</{inline}>"
            f"</{block}>"
        )

    return pattern.sub(replace, source)


class MarkupRepairer(HTMLParser):
    """Balance fragment tags, dropping orphan closers and closing open wrappers."""

    VOID_TAGS = {
        "area", "base", "br", "col", "embed", "hr", "img", "input", "link", "meta",
        "param", "source", "track", "wbr",
    }
    P_BLOCK_STARTS = {
        "address", "article", "aside", "blockquote", "div", "dl", "fieldset", "footer",
        "form", "h1", "h2", "h3", "h4", "h5", "h6", "header", "hgroup", "hr", "main",
        "menu", "nav", "ol", "p", "pre", "section", "table", "ul",
    }

    def __init__(self, source: str) -> None:
        super().__init__(convert_charrefs=False)
        self.source = source
        self.line_offsets = [0]
        self.line_offsets.extend(index + 1 for index, char in enumerate(source) if char == "\n")
        self.stack: list[str] = []
        self.edits: list[tuple[int, int, str]] = []

    def source_position(self) -> int:
        return _source_offset(self.source, self.line_offsets, self.getpos())

    def _close_from(self, index: int, position: int) -> None:
        closing = "".join(f"</{tag}>" for tag in reversed(self.stack[index:]))
        if closing:
            self.edits.append((position, position, closing))
        del self.stack[index:]

    def _close_optional_before(self, tag: str, position: int) -> None:
        candidates = []
        if tag in self.P_BLOCK_STARTS and "p" in self.stack:
            candidates.append(self.stack.index("p"))
        if tag == "li" and "li" in self.stack:
            candidates.append(len(self.stack) - 1 - self.stack[::-1].index("li"))
        if tag in {"dt", "dd"} and any(item in {"dt", "dd"} for item in self.stack):
            candidates.append(max(i for i, item in enumerate(self.stack) if item in {"dt", "dd"}))
        if tag in {"td", "th"} and any(item in {"td", "th"} for item in self.stack):
            candidates.append(max(i for i, item in enumerate(self.stack) if item in {"td", "th"}))
        if tag == "tr":
            if any(item in {"td", "th"} for item in self.stack):
                candidates.append(max(i for i, item in enumerate(self.stack) if item in {"td", "th"}))
            if "tr" in self.stack:
                candidates.append(max(i for i, item in enumerate(self.stack) if item == "tr"))
        if tag in {"thead", "tbody", "tfoot"}:
            for candidate in ({"td", "th"}, {"tr"}):
                if any(item in candidate for item in self.stack):
                    candidates.append(max(i for i, item in enumerate(self.stack) if item in candidate))
            if any(item in {"thead", "tbody", "tfoot"} for item in self.stack):
                candidates.append(max(i for i, item in enumerate(self.stack) if item in {"thead", "tbody", "tfoot"}))
        if tag == "option" and "option" in self.stack:
            candidates.append(max(i for i, item in enumerate(self.stack) if item == "option"))
        if candidates:
            self._close_from(min(candidates), position)

    def handle_starttag(self, tag: str, attrs: list[tuple[str, str | None]]) -> None:
        position = self.source_position()
        self._close_optional_before(tag, position)
        if tag not in self.VOID_TAGS:
            self.stack.append(tag)

    def handle_startendtag(self, tag: str, attrs: list[tuple[str, str | None]]) -> None:
        return

    def handle_endtag(self, tag: str) -> None:
        start = self.source_position()
        close = self.source.find(">", start)
        end = close + 1 if close >= 0 else len(self.source)
        if tag in self.VOID_TAGS:
            self.edits.append((start, end, ""))
            return
        if tag not in self.stack:
            self.edits.append((start, end, ""))
            return
        index = len(self.stack) - 1 - self.stack[::-1].index(tag)
        if index + 1 < len(self.stack):
            self._close_from(index + 1, start)
        self.stack.pop(index)

    def close(self) -> None:
        super().close()
        if self.stack:
            self.edits.append((len(self.source), len(self.source), "".join(f"</{tag}>" for tag in reversed(self.stack))))


def normalize_article_fragment(fragment: str) -> str:
    """Repair article HTML structure and heading levels without changing its text."""
    fragment = _normalize_heading_levels(fragment)
    fragment = _normalize_inline_block_wrappers(fragment)
    repairer = MarkupRepairer(fragment)
    repairer.feed(fragment)
    repairer.close()
    return _apply_edits(fragment, repairer.edits)


def reader_url(base_url: str, book_id: str, section_id: str | None = None) -> str:
    query = f"?book={quote(book_id, safe='-._~')}"
    if section_id is not None:
        query += f"&section={quote(section_id, safe='-._~')}"
    return base_url + query


def book_url(base_url: str, book_id: str) -> str:
    return base_url + "books/" + safe_segment(book_id, "book ID") + "/"


def article_url(base_url: str, book_id: str, section_id: str) -> str:
    return (
        base_url
        + "texts/"
        + safe_segment(book_id, "book ID")
        + "/"
        + safe_segment(section_id, "section ID")
        + "/"
    )


def author_url(base_url: str, author_id: str) -> str:
    return base_url + "authors/" + safe_segment(author_id, "author ID") + "/"


